#!/usr/bin/env python3
"""Build the German and Spanish pages of crd-berlin.de.

    python3 tools/build_languages.py

index.html (English) is the source. Texts marked with data-i18n="key" are
replaced with the German / Spanish translations from assets/js/i18n.js and
written to de/index.html and es/index.html, so every language has its own
URL that search engines and AI assistants can read.

The script also (re)generates the structured data (JSON-LD) block in all
three pages. Run it again after changing texts in index.html or i18n.js.
"""

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://crd-berlin.de"
LANGS = {
    "en": {"path": "/", "locale": "en_GB", "names": ["German", "English", "Spanish"]},
    "de": {"path": "/de/", "locale": "de_DE", "names": ["Deutsch", "Englisch", "Spanisch"]},
    "es": {"path": "/es/", "locale": "es_ES", "names": ["alemán", "inglés", "español"]},
}

ELEMENT = re.compile(r'(<(\w+)\b[^>]*\sdata-i18n="([^"]+)"[^>]*>)(.*?)(</\2>)', re.S)
SD_START = "    <!-- structured-data:start (generated by tools/build_languages.py) -->"
SD_END = "    <!-- structured-data:end -->"


def load_dict():
    src = (ROOT / "assets/js/i18n.js").read_text(encoding="utf-8")
    return json.loads(src[src.index("{"): src.rindex("}") + 1])


def english_texts(page):
    texts = {}
    for m in ELEMENT.finditer(page):
        texts.setdefault(m.group(3), re.sub(r"\s+", " ", m.group(4)).strip())
    return texts


def plain(text):
    text = re.sub(r"<[^>]+>", "", text)
    return html.unescape(re.sub(r"\s+", " ", text)).replace("→", "").strip()


def structured_data(lang, tx):
    """tx(key) returns the text for this language."""
    url = SITE + LANGS[lang]["path"]
    business_id = SITE + "/#business"

    services = []
    for key in ["s2", "s5", "s1", "s4"]:
        services.append({
            "@type": "Offer",
            "itemOffered": {
                "@type": "Service",
                "name": plain(tx(key + ".title")),
                "description": plain(tx(key + ".text")),
                "areaServed": {"@type": "City", "name": "Berlin"},
                "provider": {"@id": business_id},
            },
        })

    faq = []
    i = 1
    while tx("faq.q%d" % i):
        faq.append({
            "@type": "Question",
            "name": plain(tx("faq.q%d" % i)),
            "acceptedAnswer": {"@type": "Answer", "text": plain(tx("faq.a%d" % i))},
        })
        i += 1

    data = {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": ["LocalBusiness", "ProfessionalService"],
                "@id": business_id,
                "name": "CRD Berlin",
                "alternateName": ["Carlos Richter Dienstleistungen", "CRD"],
                "description": plain(tx("meta.description")),
                "url": SITE + "/",
                "logo": SITE + "/assets/images/logo-dark.png",
                "image": SITE + "/assets/images/og-image.jpg",
                "email": "info@crd-berlin.de",
                "telephone": "+49 1575 6614358",
                "address": {
                    "@type": "PostalAddress",
                    "streetAddress": "Rathenower Str. 67",
                    "postalCode": "10559",
                    "addressLocality": "Berlin",
                    "addressRegion": "Berlin",
                    "addressCountry": "DE",
                },
                "areaServed": {"@type": "City", "name": "Berlin"},
                "knowsLanguage": ["de", "en", "es"],
                "founder": {"@type": "Person", "name": "Carlos Richter Moreno"},
                "openingHoursSpecification": {
                    "@type": "OpeningHoursSpecification",
                    "dayOfWeek": ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
                    "opens": "00:00",
                    "closes": "23:59",
                },
                "contactPoint": {
                    "@type": "ContactPoint",
                    "contactType": "customer service",
                    "telephone": "+49 1575 6614358",
                    "email": "info@crd-berlin.de",
                    "availableLanguage": LANGS[lang]["names"],
                    "areaServed": "DE",
                },
                "hasOfferCatalog": {
                    "@type": "OfferCatalog",
                    "name": plain(tx("services.label")),
                    "itemListElement": services,
                },
            },
            {
                "@type": "WebPage",
                "@id": url + "#webpage",
                "url": url,
                "name": plain(tx("meta.title")),
                "inLanguage": lang,
                "about": {"@id": business_id},
            },
            {
                "@type": "FAQPage",
                "@id": url + "#faq",
                "inLanguage": lang,
                "mainEntity": faq,
            },
        ],
    }
    body = json.dumps(data, ensure_ascii=False, indent=2).replace("</", "<\\/")
    body = "\n".join("    " + line for line in body.splitlines())
    return SD_START + '\n    <script type="application/ld+json">\n' + body + "\n    </script>\n" + SD_END


def replace_structured_data(page, block):
    a = page.index(SD_START)
    b = page.index(SD_END) + len(SD_END)
    return page[:a] + block + page[b:]


def relative_to_subfolder(page):
    def fix(m):
        attr, value = m.group(1), m.group(2)
        if re.match(r"(https?:|mailto:|tel:|#|/|data:)", value):
            return m.group(0)
        return '%s="../%s"' % (attr, value)
    return re.sub(r'\b(src|href|srcset)="([^"]*)"', fix, page)


def build_language(source, lang, d, en):
    tr = d[lang]
    page = source

    def element(m):
        key = m.group(3)
        if key not in tr:
            raise SystemExit("Missing %s translation for '%s'" % (lang, key))
        return m.group(1) + tr[key] + m.group(5)

    page = ELEMENT.sub(element, page)

    title = html.escape(tr["meta.title"], quote=False)
    desc = html.escape(tr["meta.description"], quote=True)
    url = SITE + LANGS[lang]["path"]

    page = page.replace('<html lang="en">', '<html lang="%s">' % lang, 1)
    page = re.sub(r"<title>.*?</title>", "<title>%s</title>" % title, page, count=1, flags=re.S)
    page = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % desc, page, count=1)
    page = re.sub(r'<meta property="og:title" content="[^"]*">', '<meta property="og:title" content="%s">' % html.escape(tr["meta.title"]), page, count=1)
    page = re.sub(r'<meta property="og:description" content="[^"]*">', '<meta property="og:description" content="%s">' % desc, page, count=1)
    page = re.sub(r'<meta property="og:url" content="[^"]*">', '<meta property="og:url" content="%s">' % url, page, count=1)
    page = re.sub(r'<meta property="og:locale" content="[^"]*">', '<meta property="og:locale" content="%s">' % LANGS[lang]["locale"], page, count=1)
    page = page.replace('<link rel="canonical" href="%s/">' % SITE, '<link rel="canonical" href="%s">' % url, 1)

    # Language switch: mark the current language
    page = page.replace(' aria-current="true">EN</a>', '>EN</a>')
    page = page.replace('aria-label="%s">%s</a>' % ({"de": "Deutsch", "es": "Español"}[lang], lang.upper()),
                        'aria-label="%s" aria-current="true">%s</a>' % ({"de": "Deutsch", "es": "Español"}[lang], lang.upper()))

    def tx(key):
        return tr.get(key) or d["en"].get(key) or en.get(key, "")

    page = replace_structured_data(page, structured_data(lang, tx))
    page = relative_to_subfolder(page)
    return page


def main():
    index = ROOT / "index.html"
    source = index.read_text(encoding="utf-8")
    d = load_dict()
    en = english_texts(source)

    def tx_en(key):
        return d["en"].get(key) or en.get(key, "")

    source = replace_structured_data(source, structured_data("en", tx_en))
    index.write_text(source, encoding="utf-8")

    for lang in ["de", "es"]:
        out = ROOT / lang / "index.html"
        out.parent.mkdir(exist_ok=True)
        out.write_text(build_language(source, lang, d, en), encoding="utf-8")
        print("wrote", out.relative_to(ROOT))
    print("updated index.html structured data")


if __name__ == "__main__":
    main()
